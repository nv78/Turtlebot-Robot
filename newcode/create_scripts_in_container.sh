# Function to check ROS status
check_ros_status() {
    echo -e "${CYAN}Checking ROS Status...${NC}"
    echo ""
    
    # Check if roscore is running
    if pgrep -f "roscore\|rosmaster" > /dev/null; then
        echo -e "${GREEN}✓ ROS Master is running${NC}"
    else
        echo -e "${RED}✗ ROS Master is not running${NC}"
    fi
    
    # Check active nodes
    echo ""
    echo -e "${YELLOW}Active ROS Nodes:${NC}"
    if command -v rosnode &> /dev/null; then
        rosnode list 2>/dev/null | while read node; do
            echo -e "  ${GREEN}•${NC} $node"
        done
    else
        echo -e "${RED}  No ROS nodes detected${NC}"
    fi
    
    echo ""
    echo -e "${YELLOW}Press any key to continue...${NC}"
    read -n 1
}

# Function to view available maps
view_maps() {
    echo -e "${CYAN}Available Maps:${NC}"
    echo ""
    
    if [ -d "/turtlebot_ws/maps" ] && [ "$(ls -A /turtlebot_ws/maps/*.yaml 2>/dev/null)" ]; then
        cd /turtlebot_ws/maps
        for map_file in *.yaml; do
            if [ -f "$map_file" ]; then
                map_name=$(basename "$map_file" .yaml)
                map_size=$(du -h "$map_file" 2>/dev/null | cut -f1)
                echo -e "  ${GREEN}•${NC} $map_name ${YELLOW}($map_size)${NC}"
            fi
        done
    else
        echo -e "${RED}  No maps found in /turtlebot_ws/maps/${NC}"
        echo -e "${YELLOW}  Create maps using SLAM (options 3-5)${NC}"
    fi
    
    echo ""
    echo -e "${YELLOW}Press any key to continue...${NC}"
    read -n 1
}

# Function to kill all ROS nodes
kill_ros_nodes() {
    echo -e "${RED}Killing all ROS nodes...${NC}"
    
    # Kill specific ROS processes
    pkill -f "roscore\|rosmaster\|gzserver\|gzclient\|rviz"
    pkill -f "slam_gmapping\|cartographer\|map_server"
    pkill -f "move_base\|amcl"
    
    echo -e "${GREEN}All ROS processes terminated${NC}"
    echo ""
    echo -e "${YELLOW}Press any key to continue...${NC}"
    read -n 1
}

# Function to run scripts in new terminal
run_in_terminal() {
    local script_name=$1
    local title=$2
    
    if [ -f "/turtlebot_ws/scripts/$script_name" ]; then
        # Make script executable
        chmod +x "/turtlebot_ws/scripts/$script_name"
        
        # Run in new xterm window
        xterm -title "$title" -e "cd /turtlebot_ws/scripts && ./$script_name; echo 'Press any key to close...'; read -n 1" &
    else
        echo -e "${RED}Error: Script $script_name not found!${NC}"
        echo -e "${YELLOW}Press any key to continue...${NC}"
        read -n 1
    fi
}

# Main program loop
main() {
    while true; do
        show_menu
        echo -n "Enter your choice: "
        read choice
        
        case $choice in
            1)
                echo -e "${GREEN}Launching Gazebo World...${NC}"
                run_in_terminal "01_launch_gazebo_world.sh" "Gazebo World"
                ;;
            2)
                echo -e "${GREEN}Launching Gazebo House...${NC}"
                run_in_terminal "07_launch_gazebo_house.sh" "Gazebo House"
                ;;
            3)
                echo -e "${GREEN}Starting SLAM with gmapping...${NC}"
                run_in_terminal "02_launch_slam_gmapping.sh" "SLAM gmapping"
                ;;
            4)
                echo -e "${GREEN}Starting SLAM with Cartographer...${NC}"
                run_in_terminal "03_launch_slam_cartographer.sh" "SLAM Cartographer"
                ;;
            5)
                echo -e "${GREEN}Saving map...${NC}"
                run_in_terminal "05_save_map.sh" "Save Map"
                ;;
            6)
                echo -e "${GREEN}Launching Navigation...${NC}"
                run_in_terminal "06_launch_navigation.sh" "Navigation"
                ;;
            7)
                echo -e "${GREEN}Starting Teleop Control...${NC}"
                run_in_terminal "04_teleop_control.sh" "Teleop Control"
                ;;
            8)
                echo -e "${GREEN}Starting Autonomous Exploration...${NC}"
                run_in_terminal "08_autonomous_exploration.sh" "Autonomous Exploration"
                ;;
            9)
                check_ros_status
                ;;
            10)
                view_maps
                ;;
            11)
                kill_ros_nodes
                ;;
            h|H)
                show_help
                ;;
            q|Q)
                echo -e "${GREEN}Goodbye!${NC}"
                exit 0
                ;;
            *)
                echo -e "${RED}Invalid option. Please try again.${NC}"
                sleep 1
                ;;
        esac
    done
}

