# Function to show help
show_help() {
    clear
    echo -e "${CYAN}=========================================${NC}"
    echo -e "${CYAN}       TurtleBot3 Help & Instructions${NC}"
    echo -e "${CYAN}=========================================${NC}"
    echo ""
    echo -e "${GREEN}TYPICAL WORKFLOW FOR SLAM:${NC}"
    echo -e "  1. Start Gazebo simulation (option 1 or 2)"
    echo -e "  2. Start SLAM (option 3 or 4) in a new terminal"
    echo -e "  3. Use teleop control (option 7) to move robot around"
    echo -e "  4. Save the map (option 5) when mapping is complete"
    echo ""
    echo -e "${GREEN}TYPICAL WORKFLOW FOR NAVIGATION:${NC}"
    echo -e "  1. Start Gazebo simulation (option 1 or 2)"
    echo -e "  2. Launch navigation (option 6) with a saved map"
    echo -e "  3. Use RViz to set navigation goals with '2D Nav Goal'"
    echo ""
    echo -e "${GREEN}AUTONOMOUS EXPLORATION:${NC}"
    echo -e "  1. Start Gazebo simulation (option 1 or 2)"
