    echo -e "  ${YELLOW}3)${NC} Start SLAM with gmapping"
    echo -e "  ${YELLOW}4)${NC} Start SLAM with Cartographer"
    echo -e "  ${YELLOW}5)${NC} Save current map"
    echo ""
    echo -e "${GREEN}NAVIGATION:${NC}"
    echo -e "  ${YELLOW}6)${NC} Launch Navigation with saved map"
    echo -e "  ${YELLOW}7)${NC} Keyboard Teleop Control"
    echo ""
    echo -e "${GREEN}AUTONOMOUS BEHAVIORS:${NC}"
