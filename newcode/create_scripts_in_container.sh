    echo ""
    echo -e "${GREEN}UTILITIES:${NC}"
    echo -e "  ${YELLOW}9)${NC} Check ROS Status"
    echo -e "  ${YELLOW}10)${NC} View Available Maps"
    echo -e "  ${YELLOW}11)${NC} Kill All ROS Nodes"
    echo ""
    echo -e "${GREEN}HELP & INFO:${NC}"
    echo -e "  ${YELLOW}h)${NC} Show Help & Usage Instructions"
