    echo -e "  3. Run autonomous exploration (option 8)"
    echo -e "  4. Save the map (option 5) when exploration is complete"
    echo ""
    echo -e "${GREEN}IMPORTANT NOTES:${NC}"
    echo -e "  • Run commands in separate terminal windows"
    echo -e "  • Gazebo simulation must be running before SLAM/Navigation"
    echo -e "  • Use CTRL+C to stop any running process"
    echo -e "  • Maps are saved in /turtlebot_ws/maps/"
    echo ""
    echo -e "${YELLOW}Press any key to return to menu...${NC}"
