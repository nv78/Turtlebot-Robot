#!/bin/bash

# Save Map Script
# This script saves the map generated by SLAM to a file
# Run this while SLAM is active to save the current map

echo "========================================="
echo "TurtleBot3 Map Saving"
echo "========================================="

# Source ROS environment
source /opt/ros/noetic/setup.bash
source /turtlebot_ws/devel/setup.bash

# Create maps directory if it doesn't exist
mkdir -p /turtlebot_ws/maps

# Get current timestamp for unique filename
TIMESTAMP=$(date +%Y%m%d_%H%M%S)
MAP_NAME="map_${TIMESTAMP}"

# Check if map server is running
if ! rosnode list | grep -q "/map_server\|/slam_gmapping\|/cartographer"; then
    echo "ERROR: No SLAM node detected!"
    echo "Please run SLAM first using:"
    echo "  ./02_launch_slam_gmapping.sh  OR"
    echo "  ./03_launch_slam_cartographer.sh"
    exit 1
fi

echo "Saving map as: ${MAP_NAME}"
echo "Location: /turtlebot_ws/maps/${MAP_NAME}"
echo ""

# Save the map
cd /turtlebot_ws/maps
rosrun map_server map_saver -f ${MAP_NAME}

if [ $? -eq 0 ]; then
    echo ""
    echo "========================================="
    echo "Map saved successfully!"
    echo "Files created:"
    echo "  ${MAP_NAME}.yaml (map metadata)"
    echo "  ${MAP_NAME}.pgm  (map image)"
    echo "Location: /turtlebot_ws/maps/"
    echo "========================================="
    
    # List all available maps
    echo ""
    echo "Available maps:"
    ls -la /turtlebot_ws/maps/*.yaml 2>/dev/null | awk '{print "  " $9}' | sed 's/\.yaml$//'
else
    echo "ERROR: Failed to save map!"
    exit 1
fi
EOF

